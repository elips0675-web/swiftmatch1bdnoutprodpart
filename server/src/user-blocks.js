/**
 * Предикат «эти два пользователя не заблокировали друг друга» (этап 22, P0-D).
 *
 * Направление проверки — обе стороны, как в `social.js:141`: если я заблокировал
 * человека, он мне не нужен в выдаче; если он заблокировал меня — его я тоже
 * видеть не должен. Предикат живёт в SQL, а не в отдельном запросе, по
 * причине, зафиксированной ещё на этапе 11: отдельная проверка даёт окно гонки
 * между «проверил» и «прочитал», а здесь блок может прийти в любой момент.
 *
 * Возвращает `{ sql, params }`, а не строку: зрителя в SQL нельзя вставлять
 * литералом, поэтому два параметра едут в общий массив запроса.
 */
export function notBlocked(alias, viewerId) {
  return {
    sql: `NOT EXISTS (
             SELECT 1 FROM user_blocks ub
             WHERE (ub.blocker_id = ? AND ub.blocked_id = ${alias}.id)
                OR (ub.blocker_id = ${alias}.id AND ub.blocked_id = ?)
           )`,
    params: [viewerId, viewerId],
  }
}
